// generate-talos-ts emits TypeScript interfaces for Talos COSI resource specs.
//
// It reads the yaml struct tags from the actual Go types (the source of truth
// for the wire format, since COSI resources are YAML-serialised through the
// machinery) rather than the proto files in api/resource/definitions, which
// define the gRPC API surface and use different field names.
//
// Usage:
//
//	go run ./hack/generate-talos-ts [output-dir]
//
// output-dir defaults to frontend/src/api/talos.
